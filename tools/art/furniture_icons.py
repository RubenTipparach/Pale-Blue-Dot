def paint(rows):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        assert len(row) == 16, (y, row)
        for x, ch in enumerate(row):
            if ch in PAL:
                im.putpixel((x, y), PAL[ch] + (255,))
    # the 1 px outline round everything drawn
    px = im.load()
    out = im.copy()
    for y in range(16):
        for x in range(16):
            if px[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                u, v = x + dx, y + dy
                if 0 <= u < 16 and 0 <= v < 16 and px[u, v][3] and px[u, v][:3] != OUTLINE:
                    out.putpixel((x, y), OUTLINE + (255,))
                    break
    return out


def main(argv):
    made = {}
    for name, rows in ICONS.items():
        im = paint(rows)
        made[name] = im
        if name == "carpenter-bench":
            # A station's slot icon, beside the workbench's.
            im.save(ROOT / "assets" / "items" / "stations" / "carpenter.png")
        else:
            im.save(OUT / f"{name}.png")
    # Build mode's Furniture tool: the chair.
    made["chair"].resize((32, 32), Image.NEAREST).save(
        ROOT / "assets" / "textures" / "ui" / "build" / "furniture.png"
    )
    if "--sheet" in argv:
        path = argv[argv.index("--sheet") + 1]
        sheet = Image.new("RGBA", (len(made) * 136, 136), (40, 38, 34, 255))
        for k, im in enumerate(made.values()):
            big = im.resize((128, 128), Image.NEAREST)
            sheet.paste(big, (k * 136 + 4, 4), big)
        sheet.save(path)


if __name__ == "__main__":
    main(sys.argv[1:])
