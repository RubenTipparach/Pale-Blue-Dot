def rgba(h):
    return ((h >> 16) & 255, (h >> 8) & 255, h & 255, 255)


def from_ascii(art):
    rows = [r for r in art.strip("\n").split("\n")]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch in PAL:
                im.putpixel((x, y), rgba(PAL[ch]))
    return im


def wheel():
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    cx = cy = 7.5
    for y in range(16):
        for x in range(16):
            dx, dy = x - cx, y - cy
            d = (dx * dx + dy * dy) ** 0.5
            if 5.6 <= d <= 7.0:
                im.putpixel((x, y), rgba(PAL["I"] if dx + dy < 0 else PAL["i"]))
            elif 4.6 <= d < 5.6:
                im.putpixel((x, y), rgba(PAL["W"] if dx + dy < 0 else PAL["w"]))
            elif d < 1.6:
                im.putpixel((x, y), rgba(PAL["j"]))
            elif d < 4.6 and (abs(dx) < 0.6 or abs(dy) < 0.6 or abs(abs(dx) - abs(dy)) < 0.7):
                im.putpixel((x, y), rgba(PAL["w"]))
    return im


def outline(im):
    out = im.copy()
    for y in range(16):
        for x in range(16):
            if im.getpixel((x, y))[3]:
                continue
            for ox, oy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                u, v = x + ox, y + oy
                if 0 <= u < 16 and 0 <= v < 16 and im.getpixel((u, v))[3]:
                    out.putpixel((x, y), OUTLINE)
                    break
    return out


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, art in ICONS.items():
        im = wheel() if art is None else from_ascii(art)
        outline(im).save(OUT / f"{name}.png")
        print(OUT / f"{name}.png")


if __name__ == "__main__":
    main()
